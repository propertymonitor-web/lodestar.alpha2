#!/usr/bin/env python3
"""
make_splash.py - give a MeshCore checkout a custom boot splash (128x64 OLED).

  python tools/make_splash.py --meshcore MeshCore \
      --line "F.E.A.R." --line "TACTICAL" --line "RADIO" \
      --seconds 5 --logo logos/wolf.png --preview splash_preview.png

Up to 3 text lines. Optional logo (any PNG/JPG/GIF/BMP/WEBP) is converted to a
1-bit bitmap. Patches the companion radio, repeater, room server and sensor
boot screens. Fails with a plain-English message if something does not fit.
"""
import argparse
import os
import re
import shutil
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageOps

SCREEN_W, SCREEN_H = 128, 64
CHAR_W, CHAR_H = 6, 8          # Adafruit GFX font at text size 1
GAP = 4                        # pixels between text lines
LOGO_MAX_H = 60
LOGO_MAX_W_WITH_TEXT = 64
LOGO_MAX_W_ALONE = 124


def die(msg):
    print(f"\nERROR: {msg}\n", file=sys.stderr)
    sys.exit(1)


# ----------------------------------------------------------------- logo --
def load_logo_bits(path, invert, threshold_pct, box_w, box_h):
    """Return a (h, w) bool array, True = lit pixel."""
    try:
        im = ImageOps.exif_transpose(Image.open(path))
    except Exception as e:  # noqa: BLE001
        die(f"Could not open logo '{path}': {e}")
    rgba = im.convert("RGBA")
    arr = np.array(rgba)
    alpha = arr[..., 3]
    gray = np.array(rgba.convert("L")).astype(np.float32)

    if (alpha < 128).mean() > 0.02:
        # Transparent background: whatever is opaque is the logo.
        fg = alpha.astype(np.float32) / 255.0
    else:
        # Opaque picture: figure out the background from the border pixels.
        border = np.concatenate([gray[0, :], gray[-1, :], gray[:, 0], gray[:, -1]])
        bg = float(np.median(border))
        fg = (255.0 - gray) / 255.0 if bg >= 128 else gray / 255.0

    # Auto-crop to the logo itself.
    ys, xs = np.where(fg > 0.5)
    if len(xs) == 0:
        die("The logo looks empty (no visible artwork found). Try the 'invert' option.")
    fg = fg[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    if invert:
        fg = 1.0 - fg

    h0, w0 = fg.shape
    scale = min(box_w / w0, box_h / h0)
    w = max(1, round(w0 * scale))
    h = max(1, round(h0 * scale))
    small = Image.fromarray((fg * 255).astype(np.uint8), "L").resize((w, h), Image.LANCZOS)
    return np.array(small) >= (threshold_pct / 100.0) * 255.0


def header_text(bits):
    h, w = bits.shape
    bw = (w + 7) // 8
    data = []
    for r in range(h):
        for b in range(bw):
            v = 0
            for k in range(8):
                x = b * 8 + k
                if x < w and bits[r, x]:
                    v |= 0x80 >> k          # MSB first = Adafruit drawBitmap
            data.append(v)
    out = ["// generated by tools/make_splash.py - do not edit",
           "#pragma once",
           "#include <Arduino.h>",
           f"#define SPLASH_LOGO_W {w}",
           f"#define SPLASH_LOGO_H {h}",
           "static const uint8_t splash_logo[] PROGMEM = {"]
    for i in range(0, len(data), 12):
        out.append("  " + ", ".join(f"0x{v:02X}" for v in data[i:i + 12]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


# -------------------------------------------------------------- presets --
PRESETS = {"pulsar": ("PULSAR", "Repeater"), "hearth": ("HEARTH", "Room Server")}


def preset_splash(a):
    """The LODESTAR look: emblem on the left; LODESTAR / NAME / role / Wolf Reactive Systems (WRS) on the right."""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import lodestar_art
    name, role = PRESETS[a.preset]
    bits = np.array(lodestar_art.logo(a.preset)) > 0          # (60, 40) bool, True = lit
    lh, lw = bits.shape
    left = 2 + lw + 4
    mid = left + (SCREEN_W - left) // 2
    ops = [("logo", 2, (SCREEN_H - lh) // 2), ("text", 1, mid, 4, "LODESTAR"), ("text", 2, mid, 14, name),
           ("text", 1, mid, 36, role), ("text", 1, mid, 48, "WRS")]
    with open(os.path.join(a.meshcore, "src/helpers/ui/splash_logo.h"), "w") as f:
        f.write(header_text(bits))
    patch_files(a.meshcore, ops, False, a.seconds, True)
    render_preview(a.preview, ops, False, bits)
    summary = f"preset={a.preset} ({name}, {role}) seconds={a.seconds:g}"
    print(f"Splash ready: {summary}. Preview: {a.preview}")
    if os.environ.get("GITHUB_ACTIONS"):
        print(f"::notice title=Splash settings::{summary}")


# --------------------------------------------------------------- layout --
def layout(lines, logo_bits):
    """Return (ops, border). ops are ('logo',x,y) or ('text',size,cx,y,str)."""
    ops = []
    border = False
    n = len(lines)

    if logo_bits is not None:
        lh, lw = logo_bits.shape
        if n == 0:
            ops.append(("logo", (SCREEN_W - lw) // 2, (SCREEN_H - lh) // 2))
            return ops, border
        lx = 2
        ops.append(("logo", lx, (SCREEN_H - lh) // 2))
        left, right = lx + lw + 4, SCREEN_W - 2
        max_chars = (right - left) // CHAR_W
        for t in lines:
            if len(t) > max_chars:
                die(f'"{t}" is too long: with this logo only {max_chars} characters '
                    f"fit beside it (it has {len(t)}). Shorten the text or use a smaller logo.")
        cx = (left + right) // 2
        bh = n * CHAR_H + (n - 1) * GAP
        y = (SCREEN_H - bh) // 2
        for t in lines:
            ops.append(("text", 1, cx, y, t))
            y += CHAR_H + GAP
        return ops, border

    # text only: framed, first line big if it fits
    border = True
    sizes = []
    for i, t in enumerate(lines):
        if i == 0 and len(t) * CHAR_W * 2 <= SCREEN_W - 8:
            sizes.append(2)
        elif len(t) * CHAR_W <= SCREEN_W - 8:
            sizes.append(1)
        else:
            die(f'"{t}" is too long: at most {(SCREEN_W - 8) // CHAR_W} characters fit '
                f"on one line (it has {len(t)}).")
    total = sum(CHAR_H * s for s in sizes) + GAP * (n - 1)
    y = (SCREEN_H - total) // 2
    for s, t in zip(sizes, lines):
        ops.append(("text", s, SCREEN_W // 2, y, t))
        y += CHAR_H * s + GAP
    return ops, border


def c_string(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def c_block(ops, border, indent, d):
    p = " " * indent
    out = [f"{p}// custom splash (generated by tools/make_splash.py)",
           f"{p}{d}setColor(UIColor::primary_txt);"]
    if border:
        out.append(f"{p}{d}drawRect(0, 0, {d}width(), {d}height());")
    cur = None
    for op in ops:
        if op[0] == "logo":
            out.append(f"{p}{d}drawXbm({op[1]}, {op[2]}, splash_logo, SPLASH_LOGO_W, SPLASH_LOGO_H);")
        else:
            _, size, cx, y, text = op
            if size != cur:
                out.append(f"{p}{d}setTextSize({size});")
                cur = size
            out.append(f'{p}{d}drawTextCentered({cx}, {y}, "{c_string(text)}");')
    return "\n".join(out) + "\n"


# -------------------------------------------------------------- patching --
def patch_files(root, ops, border, seconds, with_logo):
    inc = "#include <helpers/ui/splash_logo.h>\n" if with_logo else ""
    ms = int(seconds * 1000)

    def set_millis(s, name):
        s2, n = re.subn(r"#define BOOT_SCREEN_MILLIS\s+\d+[^\n]*",
                        f"#define BOOT_SCREEN_MILLIS   {ms}   // {seconds:g} seconds (custom splash)", s, count=1)
        if n != 1:
            die(f"Upstream MeshCore changed: BOOT_SCREEN_MILLIS not found in {name}.")
        return s2

    def add_include(s):
        return s.replace('#include "UITask.h"\n', '#include "UITask.h"\n' + inc, 1) if inc else s

    # companion radio
    f = os.path.join(root, "examples/companion_radio/ui-new/UITask.cpp")
    s = open(f).read()
    s = set_millis(s, f)
    m = re.search(r"(  int render\(DisplayDriver& display\) override \{\n)(.*?)(    return 1000;)", s, re.S)
    if not m:
        die("Upstream MeshCore changed: companion SplashScreen::render() not found.")
    s = s[:m.start(2)] + c_block(ops, border, 4, "display.") + "\n" + s[m.end(2):]
    open(f, "w").write(add_include(s))

    # repeater / room server / sensor
    for d in ("simple_repeater", "simple_room_server", "simple_sensor"):
        f = os.path.join(root, f"examples/{d}/UITask.cpp")
        s = open(f).read()
        s = set_millis(s, f)
        m = re.search(r"(  if \(millis\(\)[^\n]*// boot screen\n)(.*?)(  \} else)", s, re.S)
        if not m:
            die(f"Upstream MeshCore changed: boot screen block not found in {d}.")
        s = s[:m.start(2)] + c_block(ops, border, 4, "_display->") + s[m.end(2):]
        open(f, "w").write(add_include(s))


# --------------------------------------------------------------- preview --
def render_preview(path, ops, border, logo_bits, scale=4):
    img = Image.new("RGB", (SCREEN_W, SCREEN_H), (0, 0, 0))
    px = img.load()
    for op in ops:
        if op[0] == "logo":
            h, w = logo_bits.shape
            for y in range(h):
                for x in range(w):
                    if logo_bits[y, x]:
                        px[op[1] + x, op[2] + y] = (255, 255, 255)
    img = img.resize((SCREEN_W * scale, SCREEN_H * scale), Image.NEAREST)
    d = ImageDraw.Draw(img)
    if border:
        d.rectangle([0, 0, SCREEN_W * scale - 1, SCREEN_H * scale - 1], outline=(255, 255, 255), width=scale)
    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
    for op in ops:
        if op[0] != "text":
            continue
        _, size, cx, y, text = op
        try:
            font = ImageFont.truetype(font_path, 10 * size * scale)
        except OSError:
            font = ImageFont.load_default()
        x = cx - (len(text) * CHAR_W * size) // 2
        d.text((x * scale, y * scale), text, fill=(255, 255, 255), font=font)
    # label so nobody mistakes this for a photo of the real screen
    img.save(path)


# ------------------------------------------------------------------ main --
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--meshcore", required=True, help="path to a MeshCore checkout")
    ap.add_argument("--line", action="append", default=[], help="text line (repeat up to 3 times)")
    ap.add_argument("--seconds", type=float, default=5)
    ap.add_argument("--logo", default="", help="logo file name inside logos/ (or a path)")
    ap.add_argument("--logos-dir", default="logos")
    ap.add_argument("--invert", default="false")
    ap.add_argument("--threshold", type=float, default=20,
                    help="1-99; lower = bolder logo (default 20)")
    ap.add_argument("--preview", default="splash_preview.png")
    ap.add_argument("--preset", default="", choices=["", "pulsar", "hearth"],
                    help="ready-made LODESTAR splash with its own emblem (ignores --line and --logo)")
    a = ap.parse_args()

    if a.preset:
        return preset_splash(a)
    lines = [l.strip() for l in a.line if l and l.strip() not in ("", "-")]
    if len(lines) > 3:
        die("At most 3 lines of text are supported.")
    for t in lines:
        bad = [c for c in t if not (32 <= ord(c) <= 126)]
        if bad:
            die(f'"{t}" contains characters the screen font cannot show: {"".join(sorted(set(bad)))} '
                "(plain letters, numbers and punctuation only).")
    if not 1 <= a.seconds <= 30:
        die("Seconds must be between 1 and 30.")
    if not 1 <= a.threshold <= 99:
        die("Threshold must be between 1 and 99.")

    logo_bits = None
    logo_name = a.logo.strip()
    if logo_name.lower() in ("-", "none"):
        logo_name = ""
    if logo_name:
        path = logo_name if os.path.exists(logo_name) else os.path.join(a.logos_dir, os.path.basename(logo_name))
        if not os.path.exists(path):
            have = sorted(os.listdir(a.logos_dir)) if os.path.isdir(a.logos_dir) else []
            die(f"Logo '{logo_name}' not found in the {a.logos_dir}/ folder. Files there: {have}")
        box_w = LOGO_MAX_W_WITH_TEXT if lines else LOGO_MAX_W_ALONE
        logo_bits = load_logo_bits(path, a.invert.lower() in ("1", "true", "yes"), a.threshold, box_w, LOGO_MAX_H)
    if not lines and logo_bits is None:
        die("Nothing to show: give at least one line of text or a logo.")

    ops, border = layout(lines, logo_bits)

    if logo_bits is not None:
        with open(os.path.join(a.meshcore, "src/helpers/ui/splash_logo.h"), "w") as f:
            f.write(header_text(logo_bits))
    patch_files(a.meshcore, ops, border, a.seconds, logo_bits is not None)
    render_preview(a.preview, ops, border, logo_bits)

    summary = (f"lines={lines} logo={logo_name or 'none'} "
               f"{('(' + str(logo_bits.shape[1]) + 'x' + str(logo_bits.shape[0]) + 'px) ') if logo_bits is not None else ''}"
               f"seconds={a.seconds:g}")
    print(f"Splash ready: {summary}. Preview: {a.preview}")
    if os.environ.get("GITHUB_ACTIONS"):
        print(f"::notice title=Splash settings::{summary}")


if __name__ == "__main__":
    main()
